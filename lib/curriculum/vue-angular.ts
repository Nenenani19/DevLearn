import type { LocalLessonSeed, LocalModuleSeed } from "../curriculum";

type SeedInput = Pick<
  LocalLessonSeed,
  "slug" | "title" | "summary" | "what" | "why" | "example" | "output" | "mistake" | "correction" | "labPrompt" | "question" | "answer" | "distractors"
> & Partial<Pick<LocalLessonSeed, "mistakeExplanation" | "hint" | "labCode" | "hidden" | "related">>;

function lesson(input: SeedInput, framework: "Vue" | "Angular"): LocalLessonSeed {
  return {
    ...input,
    mistakeExplanation:
      input.mistakeExplanation ?? `This example does not follow ${framework}'s data or component contract. Compare the value source, template binding, and expected result.`,
    hint: input.hint ?? "Trace the value from its source to the template, and keep state updates in the framework's intended API.",
    labCode: input.labCode ?? input.example,
  };
}

