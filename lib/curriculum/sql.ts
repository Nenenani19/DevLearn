import type { LocalLessonSeed, LocalModuleSeed } from "../curriculum";

type SeedInput = Pick<
  LocalLessonSeed,
  "slug" | "title" | "summary" | "what" | "why" | "example" | "mistake" | "correction" | "labPrompt" | "question" | "answer" | "distractors"
> & Partial<Pick<LocalLessonSeed, "mistakeExplanation" | "hint" | "labCode" | "output" | "related">>;

function lesson(input: SeedInput): LocalLessonSeed {
  return {
    ...input,
    mistakeExplanation:
      input.mistakeExplanation ?? "The query is failing because it compares a text value without using quotes or tries to run an operation on the wrong data type.",
    hint: input.hint ?? "Look for the difference between the value you want and the value the database expects.",
    labCode: input.labCode ?? input.example,
    output: input.output ?? "Example output appears here.",
  };
}

