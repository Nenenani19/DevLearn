type SeedInput = Pick<
  LocalLessonSeed,
  "slug" | "title" | "summary" | "what" | "why" | "example" | "mistake" | "correction" | "labPrompt" | "question" | "answer" | "distractors"
> & Partial<Pick<LocalLessonSeed, "mistakeExplanation" | "hint" | "labCode" | "hidden" | "related">>;

function lesson(input: SeedInput): LocalLessonSeed {
  return {
    ...input,
    mistakeExplanation:
      input.mistakeExplanation ?? "This code does not produce the intended result. Read the value types and the order of operations, then compare the result with the corrected example.",
    hint: input.hint ?? "Run the example, inspect each value, and change one part at a time.",
    labCode: input.labCode ?? input.example,
  };
}

