import type { LocalLessonSeed, LocalModuleSeed } from "../curriculum";

type SeedInput = Pick<
  LocalLessonSeed,
  "slug" | "title" | "summary" | "what" | "why" | "example" | "mistake" | "correction" | "labPrompt" | "question" | "answer" | "distractors"
> & Partial<Pick<LocalLessonSeed, "mistakeExplanation" | "hint" | "labCode" | "hidden" | "related">>;

function lesson(input: SeedInput): LocalLessonSeed {
  const command = input.example.split(/\r?\n/).find((line) => line.trim().startsWith("git "))?.trim() ?? "git command";
  const argumentsText = command.replace(/^git\s*/, "");

  return {
    ...input,
    anatomy: command,
    parts: [
      {
        token: "git",
        label: "Command-line program",
        description: "Runs a Git operation against a local repository. The lesson preview simulates output and never executes commands.",
      },
      {
        token: argumentsText,
        label: "Subcommand and arguments",
        description: input.summary,
      },
    ],
    mistakeExplanation:
      input.mistakeExplanation ?? "This command or workflow does not match the intended Git operation. Check which repository, branch, and file state the command affects before continuing.",
    hint: input.hint ?? "Read the command from left to right and identify its target before running it in a real repository.",
    labCode: input.labCode ?? input.example,
  };
}

