import type { LocalLessonSeed, LocalModuleSeed } from "../curriculum";

type SeedInput = Pick<
  LocalLessonSeed,
  "slug" | "title" | "summary" | "what" | "why" | "example" | "mistake" | "correction" | "labPrompt" | "question" | "answer" | "distractors"
> & Partial<Pick<LocalLessonSeed, "output" | "mistakeExplanation" | "hint" | "labCode" | "hidden" | "related">>;

function lesson(input: SeedInput): LocalLessonSeed {
  return {
    ...input,
    mistakeExplanation:
      input.mistakeExplanation ?? "The compiler cannot confirm that this code matches the value or API you intend to use. Add the smallest accurate type or change the value so both agree.",
    hint: input.hint ?? "Read the type on the left and the value on the right, then make their contract agree.",
    labCode: input.labCode ?? input.example,
  };
}

